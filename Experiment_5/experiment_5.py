import numpy as np
import matplotlib.pyplot as plt

# ============================================================
# INPUT SIGNAL
# ============================================================

signal = np.array([1, 2, 3, 4, 5, 6, 7, 8])

# Number of samples
N = len(signal)

# Sample indices
n = np.arange(N)

# ============================================================
# FFT
# ============================================================

fft_result = np.fft.fft(signal)

# Real and imaginary parts
fft_real = np.real(fft_result)
fft_imag = np.imag(fft_result)

# Magnitude and phase
magnitude_spectrum = np.abs(fft_result)
phase_spectrum = np.angle(fft_result)

# ============================================================
# IFFT
# ============================================================

reconstructed_signal = np.real(np.fft.ifft(fft_result))

# ============================================================
# PRINT RESULTS
# ============================================================

print("=" * 60)
print("              FFT ANALYSIS")
print("=" * 60)

print("\nOriginal Signal:")
print(signal)

print("\nFFT Result:")
for i, value in enumerate(fft_result):
    print(
        f"X[{i}] = "
        f"{value.real:.2f} "
        f"{'+' if value.imag >= 0 else '-'} "
        f"j{abs(value.imag):.2f}"
    )

print("\nMagnitude Spectrum:")
print(np.round(magnitude_spectrum, 2))

print("\nPhase Spectrum (radians):")
print(np.round(phase_spectrum, 2))

print("\nReconstructed Signal using IFFT:")
print(np.round(reconstructed_signal, 2))

# ============================================================
# PLOTTING
# ============================================================

fig, axes = plt.subplots(
    6, 1,
    figsize=(12, 18)
)

# ============================================================
# 1. ORIGINAL SIGNAL
# ============================================================

axes[0].stem(
    n,
    signal,
    linefmt='C0-',
    markerfmt='C0o',
    basefmt=' '
)

axes[0].set_title(
    "1. Original Discrete-Time Signal",
    fontsize=13,
    fontweight='bold'
)

axes[0].set_xlabel("Sample Index (n)")
axes[0].set_ylabel("Amplitude")
axes[0].set_xticks(n)
axes[0].grid(True, alpha=0.3)

# Data labels
for i, value in enumerate(signal):
    axes[0].annotate(
        f"{value}",
        (i, value),
        xytext=(0, 8),
        textcoords="offset points",
        ha="center",
        fontsize=9
    )

# ============================================================
# 2. FFT - REAL AND IMAGINARY PARTS
# ============================================================

axes[1].stem(
    n,
    fft_real,
    linefmt='C0-',
    markerfmt='C0o',
    basefmt=' ',
    label='Real Part'
)

axes[1].stem(
    n,
    fft_imag,
    linefmt='C1-',
    markerfmt='C1s',
    basefmt=' ',
    label='Imaginary Part'
)

axes[1].axhline(
    0,
    linewidth=0.8
)

axes[1].set_title(
    "2. FFT - Real and Imaginary Components",
    fontsize=13,
    fontweight='bold'
)

axes[1].set_xlabel("Frequency Index (k)")
axes[1].set_ylabel("Amplitude")
axes[1].set_xticks(n)

axes[1].legend(
    loc='upper right'
)

axes[1].grid(True, alpha=0.3)

# ------------------------------------------------------------
# REAL DATA LABELS
# ------------------------------------------------------------

for i, value in enumerate(fft_real):

    # Put real values above/below depending on sign
    offset = 10 if value >= 0 else -18

    axes[1].annotate(
        f"R={value:.2f}",
        (i, value),
        xytext=(0, offset),
        textcoords="offset points",
        ha="center",
        fontsize=8,
        fontweight="bold"
    )

# ------------------------------------------------------------
# IMAGINARY DATA LABELS
# ------------------------------------------------------------

for i, value in enumerate(fft_imag):

    # Put imaginary labels opposite the real labels
    if value >= 0:
        offset = 22
    else:
        offset = -30

    axes[1].annotate(
        f"I={value:.2f}",
        (i, value),
        xytext=(0, offset),
        textcoords="offset points",
        ha="center",
        fontsize=8,
        fontweight="bold"
    )

# ============================================================
# 3. MAGNITUDE SPECTRUM
# ============================================================

axes[2].stem(
    n,
    magnitude_spectrum,
    linefmt='C2-',
    markerfmt='C2o',
    basefmt=' '
)

axes[2].set_title(
    "3. FFT Magnitude Spectrum",
    fontsize=13,
    fontweight='bold'
)

axes[2].set_xlabel("Frequency Index (k)")
axes[2].set_ylabel("|X[k]|")
axes[2].set_xticks(n)

axes[2].grid(True, alpha=0.3)

# Magnitude values
for i, value in enumerate(magnitude_spectrum):
    axes[2].annotate(
        f"{value:.2f}",
        (i, value),
        xytext=(0, 8),
        textcoords="offset points",
        ha="center",
        fontsize=9
    )

# ============================================================
# 4. PHASE SPECTRUM
# ============================================================

axes[3].stem(
    n,
    phase_spectrum,
    linefmt='C3-',
    markerfmt='C3o',
    basefmt=' '
)

axes[3].axhline(
    0,
    linewidth=0.8
)

axes[3].set_title(
    "4. FFT Phase Spectrum",
    fontsize=13,
    fontweight='bold'
)

axes[3].set_xlabel("Frequency Index (k)")
axes[3].set_ylabel("Phase (radians)")
axes[3].set_xticks(n)

axes[3].grid(True, alpha=0.3)

# Phase values
for i, value in enumerate(phase_spectrum):

    offset = 8 if value >= 0 else -18

    axes[3].annotate(
        f"{value:.2f}",
        (i, value),
        xytext=(0, offset),
        textcoords="offset points",
        ha="center",
        fontsize=9
    )

# ============================================================
# 5. FFT COMPLEX VALUES
# ============================================================

axes[4].axis("off")

axes[4].set_title(
    "5. FFT Complex Values",
    fontsize=13,
    fontweight='bold',
    pad=15
)

# Header
axes[4].text(
    0.25,
    0.96,
    "Frequency Index",
    ha="center",
    fontsize=10,
    fontweight="bold"
)

axes[4].text(
    0.50,
    0.96,
    "Real Part",
    ha="center",
    fontsize=10,
    fontweight="bold"
)

axes[4].text(
    0.75,
    0.96,
    "Imaginary Part",
    ha="center",
    fontsize=10,
    fontweight="bold"
)

# Table-like FFT values
for i, value in enumerate(fft_result):

    y = 0.86 - i * 0.10

    axes[4].text(
        0.25,
        y,
        f"k = {i}",
        ha="center",
        fontsize=10
    )

    axes[4].text(
        0.50,
        y,
        f"{value.real:.2f}",
        ha="center",
        fontsize=10
    )

    axes[4].text(
        0.75,
        y,
        f"{value.imag:.2f}",
        ha="center",
        fontsize=10
    )

# ============================================================
# 6. RECONSTRUCTED SIGNAL
# ============================================================

axes[5].stem(
    n,
    reconstructed_signal,
    linefmt='C4-',
    markerfmt='C4o',
    basefmt=' '
)

axes[5].set_title(
    "6. Reconstructed Signal using IFFT",
    fontsize=13,
    fontweight='bold'
)

axes[5].set_xlabel("Sample Index (n)")
axes[5].set_ylabel("Amplitude")
axes[5].set_xticks(n)

axes[5].grid(True, alpha=0.3)

# Reconstructed values
for i, value in enumerate(reconstructed_signal):
    axes[5].annotate(
        f"{value:.2f}",
        (i, value),
        xytext=(0, 8),
        textcoords="offset points",
        ha="center",
        fontsize=9
    )

# ============================================================
# FINAL FIGURE SETTINGS
# ============================================================

fig.suptitle(
    "FFT Analysis of Discrete-Time Signal",
    fontsize=17,
    fontweight='bold'
)

plt.tight_layout(
    rect=[0, 0, 1, 0.97],
    h_pad=2.5
)

plt.show()

