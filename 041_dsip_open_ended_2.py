import numpy as np
import matplotlib.pyplot as plt
import librosa
import soundfile as sf
from scipy.signal import convolve
from scipy.fft import fft, ifft
from google.colab import files
import os

# ==========================================================
# Upload MP3 File
# ==========================================================
print("Upload your MP3 file")
uploaded = files.upload()

audio_path = list(uploaded.keys())[0]

print("Selected File:", audio_path)

# ==========================================================
# Load Audio
# ==========================================================
samples, sample_rate = librosa.load(
    audio_path,
    sr=None,
    mono=True
)

print("Sample Rate :", sample_rate)
print("Total Samples :", len(samples))

# Normalize
samples = samples / np.max(np.abs(samples))

# Save original wav
sf.write("original_audio.wav", samples, sample_rate)

# ==========================================================
# Impulse Responses
# ==========================================================

kernels = {

    "Low_Pass":
        np.ones(21) / 21,

    "High_Pass":
        np.array([-1,-1,-1,8,-1,-1,-1]),

    "Echo":
        np.array([1,0,0,0,0,0.6]),

    "Alternating":
        np.array([1,0,1,0,1])

}

# ==========================================================
# Plot Original
# ==========================================================

plt.figure(figsize=(15,12))

plt.subplot(len(kernels)+1,1,1)
plt.plot(samples,color="blue")
plt.title("Original Audio Signal")

plot_index = 2

# ==========================================================
# Processing
# ==========================================================

for name,kernel in kernels.items():

    print("\nProcessing:",name)

    # ----------------------------
    # Convolution
    # ----------------------------
    conv = convolve(samples,kernel,mode="same")

    conv = conv / np.max(np.abs(conv))

    conv_file = name+"_Convolved.wav"

    sf.write(
        conv_file,
        conv,
        sample_rate
    )

    # ----------------------------
    # Inverse Filtering
    # ----------------------------

    N = len(conv)

    H = fft(kernel,N)

    H[np.abs(H)<1e-5] = 1e-5

    recovered = np.real(
        ifft(
            fft(conv)/H
        )
    )

    recovered = recovered / np.max(np.abs(recovered))

    inverse_file = name+"_Inverse.wav"

    sf.write(
        inverse_file,
        recovered,
        sample_rate
    )

    print("Saved :",conv_file)
    print("Saved :",inverse_file)

    # Plot
    plt.subplot(len(kernels)+1,1,plot_index)
    plt.plot(conv,color="red")
    plt.title(name+" Convolved Signal")

    plot_index += 1

plt.tight_layout()
plt.show()

# ==========================================================
# Download Files
# ==========================================================

print("\nGenerated Files:\n")

generated_files = [
    "original_audio.wav",
    "Low_Pass_Convolved.wav",
    "Low_Pass_Inverse.wav",
    "High_Pass_Convolved.wav",
    "High_Pass_Inverse.wav",
    "Echo_Convolved.wav",
    "Echo_Inverse.wav",
    "Alternating_Convolved.wav",
    "Alternating_Inverse.wav"
]

for f in generated_files:
    if os.path.exists(f):
        print(f)

print("\nFinished Successfully!")