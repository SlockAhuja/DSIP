import numpy as np
import matplotlib.pyplot as plt

# -----------------------------------
# Linear Convolution Function
# -----------------------------------
def linear_convolution(signal1, signal2):
    return np.convolve(signal1, signal2, mode='full')

# -----------------------------------
# Circular Convolution Function
# -----------------------------------
def circular_convolution(signal1, signal2):

    fft_length = max(len(signal1), len(signal2))

    fft_signal1 = np.fft.fft(signal1, fft_length)
    fft_signal2 = np.fft.fft(signal2, fft_length)

    circular = np.fft.ifft(fft_signal1 * fft_signal2)

    return np.real(circular)

# -----------------------------------
# Input Signals
# -----------------------------------

signal1 = np.array([1,2,3,4,5])

signal2 = np.array([2,4,6,8,10])

# -----------------------------------
# Compute Convolutions
# -----------------------------------

linear = linear_convolution(signal1, signal2)

circular = circular_convolution(signal1, signal2)

# -----------------------------------
# Display Results
# -----------------------------------

print("Signal 1 =",signal1)

print("Signal 2 =",signal2)

print("\nLinear Convolution:\n")

print(linear)

print("\nCircular Convolution:\n")

print(circular)

# -----------------------------------
# Plot
# -----------------------------------

plt.figure(figsize=(12,8))

plt.subplot(2,1,1)

plt.stem(linear)

plt.title("Linear Convolution")

plt.xlabel("Sample")

plt.ylabel("Amplitude")

plt.grid(True)

plt.subplot(2,1,2)

plt.stem(circular)

plt.title("Circular Convolution")

plt.xlabel("Sample")

plt.ylabel("Amplitude")

plt.grid(True)

plt.tight_layout()

plt.show()