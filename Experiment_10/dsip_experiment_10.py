import cv2
import matplotlib.pyplot as plt
import numpy as np
import os

image_path = r"C:\Users\OM\OneDrive\Pictures\original.png"

print("File exists:", os.path.exists(image_path))

img = cv2.imread(image_path, cv2.IMREAD_GRAYSCALE)

if img is None:
    raise FileNotFoundError(
        "Image not found. Upload the image or provide its correct path."
    )

# 2. Fourier Transform
F = np.fft.fftshift(np.fft.fft2(img))
M, N = img.shape

# 3. Create frequency distance matrix
u, v = np.meshgrid(np.arange(N) - N // 2, np.arange(M) - M // 2)
D = np.sqrt(u**2 + v**2)

# 4. Low-Pass and High-Pass Filters
LPF = D < 30
HPF = D >= 30

# 5. Apply filters
smooth = np.abs(np.fft.ifft2(np.fft.ifftshift(F * LPF)))
high_pass = np.abs(np.fft.ifft2(np.fft.ifftshift(F * HPF)))
sharp = np.clip(img.astype(float) + high_pass, 0, 255)

# 6. Display images
plt.figure(figsize=(12, 4))

plt.subplot(1, 3, 1)
plt.imshow(img, cmap='gray')
plt.title('Original Image')
plt.axis('off')

plt.subplot(1, 3, 2)
plt.imshow(smooth, cmap='gray')
plt.title('LPF - Smoothening')
plt.axis('off')

plt.subplot(1, 3, 3)
plt.imshow(sharp, cmap='gray')
plt.title('HPF - Sharpening')
plt.axis('off')

plt.tight_layout()
plt.show()